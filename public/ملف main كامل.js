// ==========================================================
// Reset Filters
// ==========================================================

function resetFilters() {

    defaultFilterValues();

    context.filter = "none";

    if (img.complete && img.src) {

        context.clearRect(
            0,
            0,
            canvas.width,
            canvas.height
        );

        context.drawImage(
            originalCanvas,
            0,
            0,
            canvas.width,
            canvas.height
        );

    }

    updateFilterValues();

    filterStatus.textContent = "Original";

}





