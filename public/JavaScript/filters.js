// ==========================================================
// Filters
// ==========================================================
window.filters = [
    saturate,
    contrast,
    brightness,
    sepia,
    grayscale,
    blur,
    hueRotate,
    invert,
    opacity,
    dropShadow
];

// +++++++++++++++++++++++++++++++++++++++
// +++++++++++++++++++++++++++++++++++++++

window.filterFrame = null;



// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 



// ==========================================================
// Schedule Apply Filters
// ==========================================================
window.scheduleApplyFilters = function () {

    if (filterFrame !== null) {
        return;
    }

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    filterFrame = requestAnimationFrame(function () {

        applyFilters();

        filterFrame = null;

    });

};



// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 



// ==========================================================
// Filter Events
// ==========================================================
filters.forEach(function (filter) {

    filter.addEventListener("input", function () {

        scheduleApplyFilters();

        updateFilterValues();

        filterStatus.textContent = "Editing";

    });

});



// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 



// ==========================================================
// Apply Filters
// ==========================================================
window.applyFilters = function () {

    context.save();

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    context.clearRect(
        0,
        0,
        canvas.width,
        canvas.height
    );

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    let filterStyles = [
        `saturate(${saturate.value}%)`,
        `contrast(${contrast.value}%)`,
        `brightness(${brightness.value}%)`,
        `sepia(${sepia.value}%)`,
        `grayscale(${grayscale.value})`,
        `blur(${blur.value}px)`,
        `hue-rotate(${hueRotate.value}deg)`,
        `invert(${invert.value}%)`,
        `opacity(${opacity.value}%)`,
        `drop-shadow(0 0 ${dropShadow.value}px rgba(0, 0, 0, 0.8))`
    ];

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    context.filter = filterStyles.join(" ");

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    context.drawImage(
        originalCanvas,
        0,
        0,
        canvas.width,
        canvas.height
    );

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    context.restore();

};



// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 



// ==========================================================
// Update Filter Values
// ==========================================================
window.updateFilterValues = function () {

    let values = [
        saturate.value + "%",
        contrast.value + "%",
        brightness.value + "%",
        sepia.value + "%",
        Math.round(grayscale.value * 100) + "%",
        blur.value + "px",
        hueRotate.value + "°",
        invert.value + "%",
        opacity.value + "%",
        dropShadow.value + "px"
    ];

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    filterValues.forEach(function (filter, index) {

        filter.textContent = values[index];

    });

};



// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 



// ==========================================================
// Default Filter Values
// ==========================================================
window.defaultFilterValues = function () {

    let defaultValues = [
        "100",
        "100",
        "100",
        "0",
        "0",
        "0",
        "0",
        "0",
        "100",
        "0"
    ];

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    filters.forEach(function (filter, index) {

        filter.value = defaultValues[index];

    });

};



// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 
// ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++ 



// ==========================================================
// Reset Filters
// ==========================================================
window.resetFilters = function () {

    defaultFilterValues();

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    context.filter = "none";

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    if (img.complete && img.src) {

        context.clearRect(
            0,
            0,
            canvas.width,
            canvas.height
        );

        context.drawImage(
            originalCanvas,
            0,
            0,
            canvas.width,
            canvas.height
        );

    }

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    updateFilterValues();

    // +++++++++++++++++++++++++++++++++++++++
    // +++++++++++++++++++++++++++++++++++++++

    filterStatus.textContent = "Original";

};